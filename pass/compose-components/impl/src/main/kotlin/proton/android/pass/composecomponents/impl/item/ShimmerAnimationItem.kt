/**
 * Create a basic shimmer
 * User needs to use modifier to fix height/width etc
 */
@Composable
fun ShimmerAnimationItem(modifier: Modifier = Modifier) {
    val shimmerColorShades = listOf(
        Color.LightGray.copy(0.9f),
        Color.LightGray.copy(0.2f),
        Color.LightGray.copy(0.9f)
    )

    val transition = rememberInfiniteTransition(label = "")
    val translateAnim by transition.animateFloat(
        initialValue = 0f,
        targetValue = 1000f,
        animationSpec = infiniteRepeatable(
            tween(durationMillis = 1200, easing = FastOutSlowInEasing),
            RepeatMode.Reverse
        ),
        label = ""
    )

    val brush = Brush.linearGradient(
        colors = shimmerColorShades,
        start = Offset(10f, 10f),
        end = Offset(translateAnim, translateAnim)
    )

    ShimmerItem(
        modifier = modifier,
        brush = brush
    )
}

@Composable
private fun ShimmerItem(modifier: Modifier = Modifier, brush: Brush) {
    Spacer(
        modifier = modifier
            .background(brush = brush)
    )
}


@Preview
@Composable
fun PreviewShimmer(@PreviewParameter(ThemePreviewProvider::class) isDark: Boolean) {
    PassTheme(isDark = isDark) {
        Surface {
            ShimmerAnimationItem(
                modifier = Modifier
                    .size(50.dp)
                    .clip(shape = CircleShape)
            )
        }
    }
}



