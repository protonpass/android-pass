package proton.android.pass.browserallowlist.impl

import android.content.Context
import dagger.Binds
import dagger.Module
import dagger.hilt.InstallIn
import dagger.hilt.components.SingletonComponent
import dagger.hilt.android.qualifiers.ApplicationContext
import proton.android.pass.browserallowlist.api.PrivilegedBrowserAllowlistProvider
import javax.inject.Inject

internal class ResourcePrivilegedBrowserAllowlistProvider @Inject constructor(
    @param:ApplicationContext private val context: Context
) : PrivilegedBrowserAllowlistProvider {

    override val json: String by lazy {
        context.resources
            .openRawResource(R.raw.passkey_privileged_browsers_allowlist)
            .bufferedReader()
            .use { reader -> reader.readText() }
    }

    private companion object {
        // Vendored snapshot of Google's passkey privileged-apps allowlist, merged with
        // supplemental extras for browsers missing upstream (community browsers with
        // developer-signed official releases).
        // Upstream: https://www.gstatic.com/gpm-passkeys-privileged-apps/apps.json
        // Extras:   scripts/ci/browser_cert_extras.json (provenance recorded per entry).
        // Snapshot date: 2026-07-23. Do not fetch at runtime.
        //
        // The fdroid flavour ships an override copy of this resource at
        // app/src/fdroid/res/raw/ with the same name, additionally trusting F-Droid's
        // per-app re-signing keys (scripts/ci/browser_cert_extras_fdroid.json). Resource
        // merging makes the app-level copy win there, so re-signed browsers are trusted
        // only in fdroid builds. Both copies are regenerated by the CI sync script.
        //
        // Refresh via scripts/ci/checkPasskeyPrivilegedBrowserAllowlist.sh, which strips
        // publicly-known AOSP test keys (their private keys are public, so any app
        // could forge them) and re-merges the extras on every sync. PasskeyOriginVerifierTest
        // fails the build if a test key slips in.
        //
        // Every autofill/passkey consumer of "is this a known browser" reads this single
        // file, so a rotated signing key only needs updating in one place.
    }
}

@Module
@InstallIn(SingletonComponent::class)
internal abstract class PrivilegedBrowserAllowlistProviderModule {

    @Binds
    abstract fun bindPrivilegedBrowserAllowlistProvider(
        impl: ResourcePrivilegedBrowserAllowlistProvider
    ): PrivilegedBrowserAllowlistProvider
}
